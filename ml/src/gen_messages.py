EMOJI = ["", "", "", " 😉", " 🔥", " 💸", " 👍", " 🙏", " 😊", " ✅", " 💰", " 😅"]
SLANG = [("деньги", "бабки"), ("деньги", "деньжата"), ("тысяч", "косарей"), ("пожалуйста", "пж"),
         ("сейчас", "щас"), ("что", "чё"), ("привет", "прив"), ("карту", "карточку")]


def fill(template: str, rng: random.Random) -> str:
    out = template
    for key, values in SLOTS.items():
        while "{" + key + "}" in out:
            out = out.replace("{" + key + "}", rng.choice(values), 1)
    return out


def typo(text: str, rng: random.Random) -> str:
    chars = list(text)
    for _ in range(rng.randint(1, 2)):
        i = rng.randrange(len(chars))
        if not chars[i].isalpha():
            continue
        op = rng.random()
        if op < 0.4:
            del chars[i]
        elif op < 0.7 and i + 1 < len(chars):
            chars[i], chars[i + 1] = chars[i + 1], chars[i]
        else:
            chars.insert(i, chars[i])
    return "".join(chars)


def augment(text: str, rng: random.Random) -> str:
    if rng.random() < 0.3:
        for a, b in rng.sample(SLANG, 3):
            text = text.replace(a, b)
    if rng.random() < 0.35:
        text = typo(text, rng)
    if rng.random() < 0.3:
        text = text.lower()
    if rng.random() < 0.2:
        text = "".join(ch for ch in text if ch not in ".,!:;—")
    return text + rng.choice(EMOJI)


def llm_paraphrases(text: str, n: int = 2, url: str = "http://localhost:11434", model: str = "qwen2.5:7b-instruct") -> list[str]:
    prompt = (f"Перепиши сообщение {n} разными способами, как пишут в мессенджерах подростки "
              f"(сленг, сокращения, без имён и реальных номеров). Смысл не меняй. "
              f'Ответ — JSON-массив строк.\nСообщение: {text}')
    body = json.dumps({"model": model, "prompt": prompt, "stream": False, "format": "json"}).encode()
    req = urllib.request.Request(f"{url}/api/generate", data=body, headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            answer = json.loads(json.loads(r.read())["response"])
        items = answer if isinstance(answer, list) else next(v for v in answer.values() if isinstance(v, list))
        return [str(x) for x in items][:n]
    except Exception:
        return []


def generate(per_template: int, seed: int, use_llm: bool) -> list[dict]:
    rng = random.Random(seed)
    sources = [("drop_recruitment", "", t) for t in DROP] + \
              [("other_fraud", s, t) for s, t in OTHER] + \
              [("safe", "", t) for t in SAFE]
    rows, seen = [], set()
    for tid, (label, scheme, template) in enumerate(sources):
        made, attempts = 0, 0
        while made < per_template and attempts < per_template * 10:
            attempts += 1
            text = fill(template, rng)
            if made > 0:
                text = augment(text, rng)
            if text in seen:
                continue
            seen.add(text)
            rows.append({"text": text, "label": label, "scheme": scheme, "template_id": tid, "source": "template"})
            made += 1
        if use_llm:
            for text in llm_paraphrases(fill(template, rng)):
                if text not in seen:
                    seen.add(text)
                    rows.append({"text": text, "label": label, "scheme": scheme, "template_id": tid, "source": "llm"})
    rng.shuffle(rows)
    return rows


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    p = argparse.ArgumentParser()
    p.add_argument("--out", default="data/messages.csv")
    p.add_argument("--per-template", type=int, default=10)
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--llm", action="store_true", help="добавить перефразы через Ollama")
    args = p.parse_args()
    rows = generate(args.per_template, args.seed, args.llm)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["text", "label", "scheme", "template_id", "source"])
        w.writeheader()
        w.writerows(rows)
    counts = {}
    for r in rows:
        counts[r["label"]] = counts.get(r["label"], 0) + 1
    print(f"{len(rows)} сообщений → {out}: {counts}")
